import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { compile } from "@tailwindcss/node";
import { Scanner } from "@tailwindcss/oxide";
import { Features, transform } from "lightningcss";
import postcss from "postcss";
import selectorParser from "postcss-selector-parser";

const require = createRequire(import.meta.url);
const root = fileURLToPath(new URL("../", import.meta.url));
const source = resolve(root, "styles/cms.css");
const compiler = await compile(await readFile(source, "utf8"), {
  base: root,
  from: source,
  onDependency() {},
});
const scanner = new Scanner({
  sources: [
    { base: root, pattern: "runtime/**/*.{vue,js,ts}", negated: false },
  ],
});
const vendor = await readFile(
  require.resolve("@vuepic/vue-datepicker/dist/main.css"),
  "utf8",
);
// Flatten before scoping so nested selectors cannot escape the CMS container.
const flattened = transform({
  filename: "cms.css",
  code: Buffer.from(`${compiler.build(scanner.scan())}\n${vendor}`),
  include: Features.Nesting,
}).code.toString();
const css = postcss.parse(flattened);

css.walkAtRules("layer", (rule) => {
  if (rule.nodes) rule.replaceWith(...rule.nodes);
  else rule.remove();
});

css.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name))
    return;
  rule.selector = selectorParser((selectors) => {
    for (const selector of [...selectors.nodes]) {
      const first = selector.nodes[0];
      if (
        (first.type === "pseudo" && [":root", ":host"].includes(first.value)) ||
        (first.type === "tag" && ["html", "body"].includes(first.value))
      ) {
        first.replaceWith(selectorParser.className({ value: "cms-admin" }));
      } else {
        const onRoot = selector.clone();
        onRoot.first.spaces.before = "";
        if (onRoot.first.type === "universal") onRoot.first.remove();
        const scope = selectorParser.className({ value: "cms-admin" });
        if (onRoot.first?.type === "tag")
          onRoot.insertAfter(onRoot.first, scope);
        else onRoot.prepend(scope);
        selectors.append(onRoot);
        selector.prepend(selectorParser.combinator({ value: " " }));
        selector.prepend(selectorParser.className({ value: "cms-admin" }));
      }
    }
  }).processSync(rule.selector);
});

// Variables and keyframe names are global CSS namespaces, even with scoped selectors.
// Keep datepicker variables unchanged because its component sets some inline.
const animations = new Map();
css.walkAtRules(/keyframes$/, (rule) => {
  const name = rule.params;
  const scoped = `framecore-cms-${name}`;
  animations.set(name, scoped);
  rule.params = scoped;
});
css.walkDecls((declaration) => {
  if (
    !/(^|-)animation(?:-name)?$/.test(declaration.prop) &&
    !declaration.prop.startsWith("--animate-")
  )
    return;
  declaration.value = declaration.value.replace(
    /[\w-]+/g,
    (name) => animations.get(name) ?? name,
  );
});
const namespaceVariable = (name) =>
  /^--(?:dp-|framecore-cms-)/.test(name)
    ? name
    : name.replace("--", "--framecore-cms-");
css.walkDecls((declaration) => {
  if (declaration.prop.startsWith("--"))
    declaration.prop = namespaceVariable(declaration.prop);
  declaration.value = declaration.value.replace(
    /var\((--[\w-]+)/g,
    (_, name) => `var(${namespaceVariable(name)}`,
  );
});
css.walkAtRules("property", (rule) => {
  rule.params = namespaceVariable(rule.params);
});
const output = css.toString();
await writeFile(
  resolve(root, "runtime/cms.css"),
  `/* Generated by npm run build:css. Do not edit directly. */\n${output}\n`,
);
